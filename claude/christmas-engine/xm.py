        c.set_source_rgb(*(HAIR if beard else mix(HAIR, skin, 0.1)))
        c.set_line_width(6)
        c.set_line_cap(cairo.LINE_CAP_ROUND)
        inner = 1 if dx < 0 else -1
        if mood in ("sad", "cry", "worry"):
            c.move_to(dx - 13 + lx, ey - 15 - (0 if inner > 0 else 7))
            c.line_to(dx + 13 + lx, ey - 15 - (7 if inner > 0 else 0))
