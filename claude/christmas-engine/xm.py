def caption(c, s, a, cx, y, size, maxw):
    c.select_font_face(FONT)
    c.set_font_size(size)
    w = c.text_extents(s).x_advance
    lines = [s]
    if w > maxw:
        words = s.split()
        best = max(1, len(words) // 2)
        lines = [" ".join(words[:best]), " ".join(words[best:])]
    for i, ln in enumerate(lines):
        yy = y + (i - (len(lines) - 1)) * size * 1.22
        c.select_font_face(FONT)
        c.set_font_size(size)
        ex = c.text_extents(ln)
        c.move_to(cx - ex.width / 2 - ex.x_bearing, yy)
        c.text_path(ln)
        c.set_source_rgba(0, 0, 0, 0.62 * a)
        c.set_line_width(size * 0.17)
        c.set_line_join(cairo.LINE_JOIN_ROUND)
        c.stroke_preserve()
        c.set_source_rgba(*CREAM, a)
        c.fill()


