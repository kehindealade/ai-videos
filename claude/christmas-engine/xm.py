def gift(c, x, y, w, h, col, rib, tag=None, tilt=0.0, bow=True):
    c.save()
    c.translate(x, y)
    c.rotate(tilt)
    c.set_source_rgb(*col)
    rr(c, -w / 2, -h, w, h, 6)
    c.fill()
    c.set_source_rgb(*mix(col, INK, 0.2))
    c.rectangle(-w / 2, -h, w, h * 0.16)
    c.fill()
    c.set_source_rgb(*rib)
    c.rectangle(-w * 0.07, -h, w * 0.14, h)
    c.fill()
    c.rectangle(-w / 2, -h * 0.58, w, h * 0.12)
    c.fill()
    if bow:
        for sg in (-1, 1):
            ell(c, sg * w * 0.14, -h - w * 0.07, w * 0.17, w * 0.1)
            c.fill()
        ell(c, 0, -h - w * 0.04, w * 0.06, w * 0.06)
        c.fill()
    if tag:
        c.set_source_rgb(*CREAM)
        rr(c, w * 0.18, -h * 0.5, w * 0.32, h * 0.26, 4)
        c.fill()
        c.set_source_rgb(*INK)
        c.set_line_width(2)
        c.move_to(w * 0.2, -h * 0.46)
        c.line_to(w * 0.48, -h * 0.46)
        c.stroke()
    c.restore()


