def snowfall(c, t, n=160, wind=30, alpha=0.9, sz=1.0, y0=0, y1=H):
    for i, (fx, fy, s, sp) in enumerate(FLAKES[:n]):
        x = (fx * W + wind * t * sp + math.sin(t * 1.3 + i) * 18) % W
        y = y0 + ((fy + t * 0.09 * sp) % 1) * (y1 - y0)
        c.set_source_rgba(*SNOW, alpha * (0.4 + 0.6 * sp / 1.5))
        c.arc(x, y, s * sz * 0.6, 0, 2 * math.pi)
        c.fill()


def rain(c, t, a=1.0):
    c.set_line_width(2.5)
    for i, (fx, fy, s, sp) in enumerate(FLAKES[:120]):
        x = (fx * W - t * 80 * sp) % W
        y = ((fy + t * 1.4 * sp) % 1) * H
        c.set_source_rgba(0.75, 0.85, 1.0, 0.45 * a)
        c.move_to(x, y)
        c.line_to(x - 10, y + 40)
        c.stroke()


