        c.curve_to(-62, 76, -30, 92, 0, 92)
        c.curve_to(30, 92, 62, 76, 60, 12)
        c.curve_to(48, 40, 30, 36, 0, 40)
        c.curve_to(-30, 36, -48, 40, -60, 12)
